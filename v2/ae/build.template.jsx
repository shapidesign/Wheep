      var st = L.property("ADBE Text Properties").property("ADBE Text Document");
      var td = st.value;
      td.resetCharStyle(); td.resetParagraphStyle();
      td.font = o.face === "secolo" ? "Secolo-19" : GRETA; td.fontSize = size; td.fillColor = [1, 1, 1]; td.applyFill = true; td.applyStroke = false;
