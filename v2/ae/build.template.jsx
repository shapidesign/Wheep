/* WHEEP · the wrapped story → After Effects.
   Generated by ae/make.js from days.js / gen.js + shape.js + story-core.js. One 1080×1350 comp per person-day, 16 s, loops.
   Six scenes: intro (the name) · the feeling · what was measured · outside vs inside · the day in feelings · the two lines.
   - CONTROLS null per story: k out / k in, points, and the 5 colours. Every layer is live: edit words in the text layers.
   - Greta breathes (weight oscillates) and Secolo cuts on the beat, through Source Text expressions.
   - All timing comes from story-core.js, pasted into the expressions: the same code the web story runs. */
