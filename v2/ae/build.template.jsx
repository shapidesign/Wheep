  var SECOLO = "[\"Secolo-19\",\"Secolo-20\",\"Secolo-21\",\"Secolo-22\"]";
  var M_KEYS = [0, .34, .67, 1];

  app.beginUndoGroup("WHEEP wrapped story");
  var proj = app.project;
