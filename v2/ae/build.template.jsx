    op.property("ADBE Transform Group").property("ADBE Anchor Point").setValue([0, 0]);
    op.property("ADBE Transform Group").property("ADBE Position").setValue([0, 0]);
    var og = op.property("ADBE Root Vectors Group").addProperty("ADBE Vector Group").property("ADBE Vectors Group");
    var el = og.addProperty("ADBE Vector Shape - Ellipse");
    el.property("ADBE Vector Ellipse Size").expression = H0 + "[OPEN*3800,OPEN*3800];";
    el.property("ADBE Vector Ellipse Position").expression = H0 + "[HERO[0],HERO[1]];";
    og.addProperty("ADBE Vector Graphic - Fill").property("ADBE Vector Fill Color").expression = colExpr("feeling");

