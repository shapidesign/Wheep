    txt(d.name, 540, 930, 140, { rtl: true, align: "center", wExpr: "sGreta(T,10+80*sOut((T-.2)/1.2),10,0)", fit: 900, scene: 0 }).name = "0 · name";
    txt("זה היום שלך.", 540, 1010, 54, { rtl: true, align: "center", w: 40, scene: 0 }).name = "0 · this is your day";
