    shapes("band · outer", [{ colour: "dark", path: "var h=sHero(T-S_TRAIL[1],KO,KI);shp(N,h[3],h[2]*1.32*sBreath(T),h[0],h[1],-sSpin(T-S_TRAIL[1],N));" }]);
