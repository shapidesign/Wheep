      try { td.direction = o.rtl ? ParagraphDirection.DIRECTION_RIGHT_TO_LEFT : ParagraphDirection.DIRECTION_LEFT_TO_RIGHT; } catch (e) {}
      if (o.box) { td.autoLeading = false; td.leading = Math.round(size * 1.2); }
      // in an RTL paragraph AE reads justification from the reading direction, so flip it to land where we mean
